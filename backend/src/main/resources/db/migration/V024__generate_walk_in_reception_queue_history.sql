-- Entry transitions own their history. A direct history INSERT cannot impersonate
-- the queue trigger through ordinary SQL, even when the role has table INSERT.
CREATE FUNCTION reject_direct_walk_in_reception_queue_history_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF pg_trigger_depth() <> 2 THEN
        RAISE EXCEPTION 'walk-in reception queue history is generated by entry transitions'
            USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_walk_in_reception_queue_history_generated_only
    BEFORE INSERT ON walk_in_reception_queue_history
    FOR EACH ROW EXECUTE FUNCTION reject_direct_walk_in_reception_queue_history_insert();

CREATE FUNCTION record_walk_in_reception_queue_transition() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    actor_text TEXT;
    actor_id UUID;
    correlation TEXT;
BEGIN
    actor_text := NULLIF(current_setting('otcms.reception_actor_id', true), '');
    IF actor_text IS NULL THEN
        RAISE EXCEPTION 'reception queue transition requires an actor'
            USING ERRCODE = '23514';
    END IF;
    actor_id := actor_text::UUID;
    PERFORM 1 FROM accounts
    WHERE id = actor_id AND account_type = 'RECEPTIONIST' AND status = 'ACTIVE'
    FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'reception queue actor must be an active Receptionist'
            USING ERRCODE = '23514';
    END IF;

    correlation := NULLIF(current_setting('otcms.reception_correlation_id', true), '');
    IF correlation IS NOT NULL AND (length(correlation) > 128 OR length(trim(correlation)) = 0) THEN
        RAISE EXCEPTION 'invalid reception queue correlation ID'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO walk_in_reception_queue_history
            (queue_entry_id, from_status, to_status, actor_account_id, occurred_at, correlation_id)
        VALUES (NEW.id, NULL, 'WAITING', actor_id, clock_timestamp(), correlation);
    ELSIF OLD.status = 'WAITING' AND NEW.status = 'LEFT_RECEPTION' THEN
        INSERT INTO walk_in_reception_queue_history
            (queue_entry_id, from_status, to_status, reason, actor_account_id, occurred_at, correlation_id)
        VALUES (NEW.id, 'WAITING', 'LEFT_RECEPTION', NEW.exit_reason, actor_id, clock_timestamp(), correlation);
    ELSE
        RAISE EXCEPTION 'invalid reception queue transition' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_walk_in_reception_queue_record_transition
    AFTER INSERT OR UPDATE OF status ON walk_in_reception_queue_entries
    FOR EACH ROW EXECUTE FUNCTION record_walk_in_reception_queue_transition();
